import math 
import random
import matplotlib.pyplot as plt  # Графики для пунктов 2.5 и 2.6

# random.uniform(c - width, c + width)


random.seed(1)    # Фиксируем случайность, чтобы вывод не менялся от запуска к запуску
N_POINTS = 15000  # Сколько всего точек бросает слепой поиск
ROUNDS = 15       # Сколько раз сужается область, количество раундов
SHRINK = 0.5      # Во сколько раз уменьшается область за один этап
RUNS = 10         # Сколько запусков делаем в серии
BOUND = 5         # Текущая граница области: каждая координата от -BOUND до BOUND


# Пункт 2.4. Задаём количество отказов K, точность и коэффициент уменьшения шага
H = 1.0       # Начальная длина шага
K = 100       # Сколько неудач подряд разрешено до уменьшения шага
BETA = 0.5    # Коэффициент уменьшения шага
EPS = 0.0001  # Точность: когда шаг меньше этого числа, останавливаемся


# Пункты 1.3 и 2.2. Задаём функции f(x1, x2, ...)
def f_a(x):  # Функция а)
    return 4.5 * x[0] ** 2 - 4.5 * x[0] - 3 * x[0] * x[1] + 2 * x[1] ** 2 - 3 * x[1]

def f_b(x):  # Функция б)
    return 8 * (x[0] - 2) ** 2 + (x[1] - 5) ** 2 + 4 * (x[2] - 3) ** 2

def f_v(x):  # Функция в): функция Биля, сумма расписана на три слагаемых
    return (1.5 - x[0] * (1 - x[1])) ** 2 + (2.25 - x[0] * (1 - x[1] ** 2)) ** 2 + (2.625 - x[0] * (1 - x[1] ** 3)) ** 2

def f_g(x):  # Функция г): пример с несколькими локальными экстремумами. Двумерная функция Растригина, при n = 2
    return 20 + x[0] ** 2 + x[1] ** 2 - 10 * math.cos(2 * math.pi * x[0]) - 10 * math.cos(2 * math.pi * x[1])  # Формула

def f_test(x):  # Простая функция для проверки при любом n: минимум 0 в точке (1, 1, ..., 1)
    total = 0                      # Накапливаем сумму
    for coord in x:                # Смотрим каждую координату
        total += (coord - 1) ** 2  # Прибавляем квадрат отклонения от единицы
    return total                   # Возвращаем сумму


# Пункты 1.4 и 2.3. Логическая функция: проходит ли точка по всем ограничениям
def is_valid(x):                                                          # Проверка: лежит ли точка внутри области
    for coord in x:                                                       # Смотрим каждую координату точки
        if coord < -BOUND or coord > BOUND:                               # Координата вышла за границу
            return False                                                  # Значит, точка вне области
    return True                                                           # Все координаты в норме, точка подходит

def random_point(center, width):                                          # Случайная точка в кубе вокруг центра. Функция создает случайную точку рядом с заданным центром
    return [random.uniform(c - width, c + width) for c in center]         # Каждая координата случайна рядом с центром, отклоняет не больше чем width

def report(label, f, x):                                                  # Печать результата: подпись, значение функции, точка
    print(label, "F =", round(f(x), 4), "в точке", [round(v, 4) for v in x])  # Округляем до 4 знаков
    
def block(title):                                                         # Печать заголовка блока между двумя линиями из дефисов
    print("\n" + "-" * 70)                                                # Пустая строка и верхняя линия
    print(title)                                                          # Заголовок блока
    print("-" * 70)                                                       # Нижняя линия




# ЗАДАНИЕ 1. Метод слепого поиска

# Пункт 1.1. Метод слепого поиска: кидаем случайные точки, выбираем лучшую (1 балл)
'''
@param f        - функция, экстремум которой ищем	f_a
@param center   - центр области поиска, список координат, длина задаёт размерность n [0, 0]
@param width    - расстояние от центра до края области поиска по каждой координате	5
@param n_points	- cколько случайных точек бросить 15000
@param sign	    - что ищем: 1 - минимум, -1 - максимум	1
@param show     -	печатать ли каждую точку: True - да, False - нет
'''
def blind_search(f, center, width, n_points, sign, show=False):  # sign=1 минимум f, sign=-1 минимум -f, то есть максимум f
    best, best_value = None, math.inf          # Лучшей точки нет, начинаем с бесконечности
    for i in range(n_points):                  # Бросаем n_points точек
        x = random_point(center, width)        # Бросаем точку
        while not is_valid(x):                 # Если точка вышла за область
            x = random_point(center, width)    # Бросаем заново
        if show:                               # Точки печатаем только по просьбе, когда их мало
            report("   бросок:", f, x)         # Показываем точку и значение в ней
        if sign * f(x) < best_value:           # Новая точка лучше лучшей
            best, best_value = x, sign * f(x)  # Запоминаем её и её значение
    return best                                # Возвращаем лучшую точку


# Пункт 1.2. Модификация: локализация области поиска вблизи лучшей точки (1 балл)
'''
@param f        - функция, экстремум которой ищем	f_a
@param n	      - размерность задачи, т.е. число координат точки	2
@param n_points	- сколько точек бросить всего за все раунды. На один раунд приходится n_points // ROUNDS	15000
@param sign	    - что ищем: 1 - минимум, -1 - максимум	1
'''
def localized_search(f, n, n_points, sign):  # Слепой поиск с локализацией области
    center = [0] * n                                                  # Сначала ищем вокруг центра области
    width = BOUND                                                     # Сначала ищем по всей области
    for r in range(ROUNDS):                                           # Повторяем поиск несколько раз (r - раунд)
        x = blind_search(f, center, width, n_points // ROUNDS, sign)  # Ищем в текущей области
        if r == 0 or sign * f(x) < sign * f(center):                  # Первая найденная точка или точка лучше прежней
            center = x                                                # Новый центр области: лучшая точка
        width = width * SHRINK                                        # Сужаем область
    return center                                                     # Лучшая точка всегда лежит в центре




# ЗАДАНИЕ 2. Метод случайных направлений

# Пункт 2.1. Метод случайных направлений с возвратом при неудачном шаге (1 балл)
def random_direction(n):                         # Случайное направление длины 1
    d = random_point([0] * n, 1)                 # Случайный вектор с координатами от -1 до 1
    length = math.sqrt(sum([v * v for v in d]))  # Длина вектора по теореме Пифагора
    return [v / length for v in d]               # Делим на длину, чтобы длина стала равна 1


'''
@param f     - функция, экстремум которой ищем	f_a
@param start - начальная точка, список координат. Его длина задаёт размерность n[2, 3]
@param sign  - что ищем: 1 - минимум, -1 - максимум	1
'''
def random_directions(f, start, sign): # Сам метод. sign=1 минимум f, sign=-1 максимум f
    x = start                                          # Текущая точка: начинаем с начальной
    h = H                                              # Текущая длина шага: начинаем с начального шага (1.0)
    fails = 0                                          # Неудач подряд
    iters = 0                                          # Итераций
    path = [start]                                     # Траектория: сразу записываем в неё начальную точку
    failed = []                                        # Неудачных попыток пока нет
    while h >= EPS:                                    # Пока шаг не стал меньше точности
        iters += 1
        d = random_direction(len(x))                   # Выбираем случайное направление
        y = [x[i] + h * d[i] for i in range(len(x))]   # Пробная точка: шаг h по направлению d
        if is_valid(y) and sign * f(y) < sign * f(x):  # Точка в области и функция улучшилась
            x = y                                      # Переходим в новую точку
            fails = 0                                  # Неудачи подряд обнулились
            path.append(x)                             # Записываем точку в траекторию
        else:                                          # Шаг неудачный: x не меняем, это и есть возврат
            fails += 1                                 
            failed.append(y)                           # Записываем неудачную попытку
            if fails == K:                             # Набралось K неудач подряд
                h = h * BETA                           # Уменьшаем шаг
                fails = 0                              # Считаем неудачи заново
    return x, iters, path, failed                      # Возвращаем точку, итерации, траекторию и неудачи


'''
@param f     - функция, экстремум которой ищем f_a
@param n	   - размерность задачи, т.е. число координат точки	2
@param sign  - что ищем: 1 - минимум, -1 - максимум	1
'''
def series(f, n, sign):                   # Серия запусков метода из случайных начальных точек
    best = random_point([0] * n, BOUND)   # Первая лучшая точка берётся случайно
    values = []                           # Сюда собираем ответы всех запусков
    for r in range(RUNS):                 # Делаем RUNS запусков
        x, iters, path, failed = random_directions(f, random_point([0] * n, BOUND), sign)  # Новый запуск из новой точки
        values.append(round(f(x), 2))     # Запоминаем ответ запуска
        if sign * f(x) < sign * f(best):  # Этот запуск лучше предыдущих
            best = x                      # Запоминаем его точку
    return best, values                   # Возвращаем лучшую точку и все ответы


def draw_search(name, label, path, failed):  # Рисует один график для n = 2
    plt.figure()                                                   # Создаём новое окно графика
    plt.plot([p[0] for p in failed], [p[1] for p in failed], "rx", markersize=3, label="неудачные попытки")  # Пункт 2.6. Неудачные попытки (0,5 балла)
    plt.plot([p[0] for p in path], [p[1] for p in path], "b.-", label="траектория")  # Пункт 2.5. Траектория поиска (1 балл)
    plt.xlim(-BOUND, BOUND)                                        # Показываем только область по x1
    plt.ylim(-BOUND, BOUND)                                        # Показываем только область по x2
    plt.xlabel("x1")                                               # Подпись оси x1
    plt.ylabel("x2")                                               # Подпись оси x2
    plt.title("Функция " + name + ", поиск " + label)              # Заголовок графика
    plt.legend()                                                   # Подписи линий
    plt.savefig("график_" + name + "_" + label + ".png", dpi=120)  # Сохраняем картинку для отчёта


