# Рисует график для n = 2
def draw_search(path):
    x1_list = [p[0] for p in path]                                        # Все координаты x1 траектории
    x2_list = [p[1] for p in path]                                        # Все координаты x2 траектории
    x1_min = min(x1_list) - 1                                             # Левый край графика
    x1_max = max(x1_list) + 1                                             # Правый край графика
    x2_min = min(x2_list) - 1                                             # Нижний край графика
    x2_max = max(x2_list) + 1                                             # Верхний край графика
    grid_x1 = [x1_min + (x1_max - x1_min) * i / 100 for i in range(101)]  # 101 значение x1
    grid_x2 = [x2_min + (x2_max - x2_min) * i / 100 for i in range(101)]  # 101 значение x2
    grid_f = []                                                           # Таблица значений функции
    for b in grid_x2:                                                     # Перебираем строки таблицы
        row = []                                                          # Новая строка
        for a in grid_x1:                                                 # Перебираем столбцы таблицы
            row.append(f([a, b]))                                         # Значение функции в точке (a, b)
        grid_f.append(row)                                                # Добавляем строку в таблицу
    plt.figure()                                                          # Создаём новое окно графика
    
    # линии уровня целевой функции (+2 балла)
    lines = plt.contour(grid_x1, grid_x2, grid_f, 15, colors="gray", linewidths=0.8, linestyles="solid")  # Рисуем линии уровня
    plt.clabel(lines, fontsize=8)                                         # Подписываем значения на линиях
    # траектория поиска (+2 балла)
    plt.plot(x1_list, x2_list, "b.-", label="траектория")                 # Рисуем траекторию
    plt.plot(x1_list[-1], x2_list[-1], "ro", label="ответ")               # Отмечаем найденную точку
    plt.xlabel("x1")                                                      # Подпись оси x1
    plt.ylabel("x2")                                                      # Подпись оси x2
    plt.title("Метод градиента с дроблением шага")                        # Заголовок графика
    plt.legend(loc="upper right")                                         # Подписи линий в углу, чтобы не закрывать траекторию
    plt.savefig("график_12_1.png", dpi=120)                               # Сохраняем картинку
