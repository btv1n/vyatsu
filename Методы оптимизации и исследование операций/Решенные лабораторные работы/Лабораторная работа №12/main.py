# Реализовать на ЭВМ (на любом языке программирования) следующие методы многомерной градиентной оптимизации (для n>=2)

# В программе задавать: функцию f(x1,x2)
# Минимум функции: -4.5 в точке (2, -0.5)
# f(x₁, x₂) = x₁² − 4x₁ + 2x₂² + 2x₂. Интегрируем частные производные: ∂f/∂x₁ = 2x₁ − 4, ∂f/∂x₂ = 4x₂ + 2
def f(x):
    total = x[0] ** 2 - 4 * x[0] + 2 * x[1] ** 2 + 2 * x[1]     # Формула для x1 и x2
    for i in range(2, len(x)):                                  # Если n > 2, смотрим остальные координаты
        total += x[i] ** 2                                      # Минимум по ним будет в нуле
    return total


# В программе задавать: логическую функцию – проверку принадлежности точки области допустимых решений (т.е проверку – проходит ли точка по всем ограничениям)
def is_valid(x):                                       # Проверка: лежит ли точка внутри области
    for coord in x:                                    # Смотрим каждую координату точки
        if coord < -BOUND or coord > BOUND:            # Координата вышла за границу
            return False                               # Точка вне области
    return True                                        # Все координаты в норме, точка подходит
 

def gradient(x):                                       # Считаем градиент: список всех частных производных
    g = []                                             # Список производных
    for i in range(len(x)):                            # Считаем производную по каждой координате
        right = x.copy()                               # Копия точки для сдвига вправо
        left = x.copy()                                # Копия точки для сдвига влево
        right[i] += DELTA                              # Немного увеличиваем координату
        left[i] -= DELTA                               # Немного уменьшаем координату
        g.append((f(right) - f(left)) / (2 * DELTA))   # Разность значений делим на расстояние
    return g                                           # Возвращаем градиент


def length(v):                                         # Длина вектора по теореме Пифагора
    return math.sqrt(sum([c * c for c in v]))          # Корень из суммы квадратов координат


# Метод градиента с дроблением (коррекцией) шага вблизи минимума
'''
@param start - начальная точка, список координат. Его длина задаёт размерность n [1, 0]
@param h     - начальная длина шага 1
@param eps   - точность 0.05
@param mode  - для чего точность: "1" - для модуля градиента, "2" - для величины шага
'''
def gradient_search(start, h, eps, mode):
    x = start                                                # Текущая точка: начинаем с начальной
    steps = 0                                                # Количество шагов
    path = [start]                                           # Траектория: сразу записываем начальную точку
    while steps < MAX_STEPS:                                 # Ограничиваем число шагов
        g = gradient(x)                                      # Считаем градиент в текущей точке
        g_len = length(g)                                    # Считаем модуль градиента
        if g_len == 0:                                       # Градиент равен нулю: двигаться некуда
            break                                            # Заканчиваем поиск
        if mode == "1" and g_len < eps:                      # Модуль градиента стал меньше точности
            break                                            # Заканчиваем поиск
        if mode == "2" and h < eps:                          # Шаг стал меньше точности
            break                                            # Заканчиваем поиск
        steps += 1                                           # Начинаем новый шаг
        y = [x[i] - h * g[i] / g_len for i in range(len(x))] # Следующая точка: сдвигаемся на длину h в сторону, где функция убывает быстрее всего
        
        # Выводит координаты найденной точки и шаг
        print("Шаг", steps, "| h =", h, "| точка", [round(v, 4) for v in y], "| F =", round(f(y), 4), end=" ")
        
        if is_valid(y) and f(y) < f(x):                      # Точка в области и функция уменьшилась
            print("| переходим")                             # Сообщаем об переходе
            x = y                                            # Переходим в новую точку
            path.append(x)                                   # Записываем точку в траекторию
        else:                                                # Функция не уменьшилась или точка вне области
            print("| дробим шаг")                            # Сообщаем о дроблении
            h = h / 2                                        # Уменьшаем шаг в 2 раза, точка x не меняется
    return x, steps, path                                    # Возвращаем ответ, число шагов и траекторию


